import { expect, test } from "@playwright/test";
import { createActiveGoal, firstTaskTitle } from "./helpers/goal-fixtures";

test("withdraws feedback before task change and retains plan and marked history after reload", async ({ page }) => {
  await createActiveGoal(page);
  const read = () => page.evaluate(async () => (await (await fetch(`/api/goals/${location.pathname.split("/").at(-1)}`, { cache: "no-store" })).json()).data);
  const initial = await read();
  const task = page.locator(".task-board__item").filter({ hasText: firstTaskTitle });
  await task.getByRole("button", { name: `开始：${firstTaskTitle}` }).click();
  await expect(task.getByText("进行中", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "报告阻碍" }).click();
  await page.getByRole("radio", { name: "缺少资源或信息" }).check();
  await page.getByLabel("补充说明（选填）").fill("撤销验证：暂缺项目资料");
  await page.getByRole("button", { name: "请教练帮我分析" }).click();
  await expect(page.getByRole("heading", { name: "最小下一步", exact: true })).toBeVisible();
  const beforeUndo = await read();
  expect(beforeUndo.undoCandidate.kind).toBe("check_in");
  let undoModelRequests = 0;
  page.on("request", request => { if (request.method() === "POST" && new URL(request.url()).pathname === "/api/agent/turn") undoModelRequests++; });
  await page.getByRole("button", { name: "撤销上一次修改" }).click();
  await expect(page.getByRole("heading", { name: "最小下一步", exact: true })).not.toBeVisible();
  await expect(page.getByRole("region", { name: "撤销上一次修改" })).toContainText(`任务：${firstTaskTitle}`);
  const afterFeedback = await read();
  expect(afterFeedback.tasks).toEqual(beforeUndo.tasks);
  expect(afterFeedback.currentPlan).toEqual(initial.currentPlan);
  expect(afterFeedback.checkIns[0].withdrawnAt).toEqual(expect.any(String));
  await page.getByRole("button", { name: "撤销上一次修改" }).click();
  await expect(task.getByRole("button", { name: `开始：${firstTaskTitle}` })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "当前已批准计划" })).toBeVisible();
  await page.getByText("反馈历史（1）", { exact: true }).click();
  await expect(page.getByText("已撤销", { exact: true })).toBeVisible();
  await expect(page.getByText(/撤销验证：暂缺项目资料/)).toBeVisible();
  const final = await read();
  expect(final.currentPlan).toEqual(initial.currentPlan);
  expect(final.tasks.map((row: { id: string; status: string }) => ({ id: row.id, status: row.status }))).toEqual(initial.tasks.map((row: { id: string; status: string }) => ({ id: row.id, status: row.status })));
  expect(final.canUndo).toBe(false);
  expect(undoModelRequests).toBe(0);
});
